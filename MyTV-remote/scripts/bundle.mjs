/**
 * Zero-external-dependency TypeScript bundler for MyTV Companion Remote (`INC-01`).
 * Compiles `src/services/TvRemoteService.ts` + `src/remoteApp.ts` into a single browser-ready
 * IIFE bundle at `public/app.bundle.js` using the workspace's installed `typescript` compiler.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const servicePath = path.join(projectRoot, 'src', 'services', 'TvRemoteService.ts');
const appPath = path.join(projectRoot, 'src', 'remoteApp.ts');
const outPath = path.join(projectRoot, 'public', 'app.bundle.js');

function stripModuleSyntax(source) {
  return source
    // Remove local ES module import statements (files are concatenated in dependency order)
    .replace(/^\s*import\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    // Strip `export` keyword from declarations so all symbols share the IIFE lexical scope
    .replace(/^\s*export\s+(?=(?:abstract\s+)?(?:class|interface|type|function|const|let|enum)\b)/gm, '');
}

const serviceSource = stripModuleSyntax(fs.readFileSync(servicePath, 'utf8'));
const appSource = stripModuleSyntax(fs.readFileSync(appPath, 'utf8'));

const combinedTs = `// Auto-generated by MyTV-remote/scripts/bundle.mjs — DO NOT EDIT DIRECTLY
(function () {
"use strict";

${serviceSource}

${appSource}
})();
`;

const result = ts.transpileModule(combinedTs, {
  fileName: 'app.bundle.ts',
  reportDiagnostics: true,
  compilerOptions: {
    target: ts.ScriptTarget.ES2020,
    module: ts.ModuleKind.None,
    strict: true,
    removeComments: false,
  },
});

if (result.diagnostics && result.diagnostics.length > 0) {
  const formatted = ts.formatDiagnosticsWithColorAndContext(result.diagnostics, {
    getCanonicalFileName: (f) => f,
    getCurrentDirectory: () => projectRoot,
    getNewLine: () => '\n',
  });
  console.error(formatted);
  process.exit(1);
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, result.outputText, 'utf8');
console.log(`Bundled Companion Remote -> ${path.relative(projectRoot, outPath)} (${Buffer.byteLength(result.outputText, 'utf8')} bytes)`);
